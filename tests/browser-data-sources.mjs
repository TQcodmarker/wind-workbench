// Runs against a local service; reads public caches and tests reversible selection.
// It never saves credentials or initiates either provider's acquisition.
import {chromium} from 'playwright';
import {mkdir, writeFile, readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const base=process.env.BOND_TEST_URL||'http://127.0.0.1:8765';
await mkdir('test-results',{recursive:true});
const boot=await fetch(base+'/api/bootstrap').then(r=>r.json());
assert.equal(boot.mode,'akshare','Run this check with AKShare selected');
const target=boot.latestSavedDate;
assert(target,'Need a dated public cache');
const errors=[];const checks=[];
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
 const page=await browser.newPage({viewport:{width:1440,height:960},acceptDownloads:true});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 await page.goto(base+'/workbench?date='+target);
 await page.getByRole('table',{name:'已保存个券数据',exact:true}).waitFor();
 assert.match(await page.locator('body').innerText(),/AKShare · 已有样本/);
 assert(await page.getByRole('button',{name:'更新 AKShare 数据',exact:true}).isVisible());
 checks.push('AKShare cache and source-specific update button render');
 const replacement=page.locator('summary').filter({hasText:'已获取（替代）'}).first();
 await replacement.click();
 assert.match(await page.locator('body').innerText(),/指数.*久期参考/);
 checks.push('Substitutes show the actual index metric and source');
 const csvEvent=page.waitForEvent('download');
 await page.getByRole('button',{name:'导出已有个券',exact:true}).click();
 const csv=await csvEvent;
 const csvPath='test-results/akshare-ui-export.csv';
 await csv.saveAs(csvPath);
 const text=await readFile(csvPath,'utf8');
 assert.match(text,/AKShare/);assert.match(text,/实际指标/);
 assert.match(text,/指数平均市值法久期参考/);
 checks.push('CSV preserves source, actual metric, unit and proxy meaning');
 await page.screenshot({path:'test-results/akshare-workbench.png',fullPage:true});
 await page.getByRole('button',{name:'数据源',exact:true}).click();
 await page.getByRole('heading',{name:'数据源',exact:true}).waitFor();
 await page.getByLabel('AKShare 数据状态',{exact:true}).getByText('1.18.94',{exact:true}).waitFor();
 assert.match(await page.getByLabel('AKShare 数据状态',{exact:true}).innerText(),/1\.18\.94/);
 assert(await page.getByLabel('Wind Key',{exact:true}).isVisible());
 assert(await page.getByRole('button',{name:'验证真实连接',exact:true}).isVisible());
 assert(await page.getByRole('button',{name:'发现 Wind 工具',exact:true}).isVisible());
 assert(await page.getByRole('button',{name:'核验工作台数据',exact:true}).isVisible());
 await page.screenshot({path:'test-results/akshare-sources.png',fullPage:true});
 checks.push('AKShare installed status and all Wind configuration actions remain');
 await page.getByRole('button',{name:'切换到 Wind',exact:true}).click();
 await page.getByRole('button',{name:'切换到 AKShare',exact:true}).waitFor();
 assert.equal((await fetch(base+'/api/bootstrap').then(r=>r.json())).mode,'wind');
 await page.reload();
 await page.getByRole('button',{name:'切换到 AKShare',exact:true}).waitFor();
 await page.getByRole('button',{name:'估值工作台',exact:true}).click();
 await page.getByRole('heading',{name:'地方债估值',exact:true}).waitFor();
 assert.match(await page.locator('body').innerText(),/Wind/);
 checks.push('Wind selection persists across reload and its workbench remains usable');
 await page.getByRole('button',{name:'数据源',exact:true}).click();
 await page.getByRole('button',{name:'切换到 AKShare',exact:true}).click();
 await page.getByRole('button',{name:'当前使用 AKShare',exact:true}).waitFor();
 assert.equal((await fetch(base+'/api/bootstrap').then(r=>r.json())).mode,'akshare');
 await page.getByRole('button',{name:'估值工作台',exact:true}).click();
 await page.getByRole('table',{name:'已保存个券数据',exact:true}).waitFor();
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'test-results/akshare-mobile.png',fullPage:true});
 checks.push('AKShare is restored and the mobile page has no outer overflow');
 assert.deepEqual(errors,[]);
 checks.push('No browser script or console errors');
 await writeFile('test-results/browser-data-sources.json',JSON.stringify({target,checks,errors},null,2));
 console.log(JSON.stringify({passed:checks.length,checks},null,2));
}finally{
 await browser.close();
 const current=await fetch(base+'/api/bootstrap').then(r=>r.json());
 if(current.mode!=='akshare')await fetch(base+'/api/source/provider',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({provider:'akshare'})});
}
